vim.opt.runtimepath:prepend(vim.fn.fnamemodify(arg[0], ':p:h:h'))
vim.env.SHELL = '/bin/sh'
local terminal = require('terminal')
local state = require('terminal.state')
terminal.setup({ keys = false, set_buffer_name = false })
local function settle() vim.wait(160, function() return false end) end
local destination = vim.api.nvim_get_current_tabpage()
local existing = terminal.new()
settle()
local win = vim.api.nvim_get_current_win()
local previous = vim.t.term_prev_tab_id
vim.cmd('tabnew')
local first = terminal.new()
local second = terminal.vsplit()
terminal.rename('Worker', second)
local hidden = terminal.new()
settle()
local source_order = state.get_term_order()
local layout = vim.deepcopy(source_order[1].layout)
local id = source_order[1].id
vim.cmd('tabclose')
settle()
local tabs = state.get_tabs()
assert(vim.api.nvim_get_current_tabpage() == destination)
assert(vim.api.nvim_get_current_win() == win and vim.api.nvim_get_current_buf() == existing)
assert(state.is_term_open() and vim.t.term_tab_idx == 1 and vim.t.term_prev_tab_id == previous)
assert(#tabs == 3 and tabs[2].id == id and vim.deep_equal(tabs[2].layout, layout))
assert(tabs[2].bufs[1] == first and tabs[2].bufs[2] == second and tabs[3].bufs[1] == hidden)
assert(vim.b[second].terminal_custom_name == 'Worker')
for _, buf in ipairs({ first, second, hidden }) do
	assert(vim.b[buf].term_owner_tab == destination and state.find_pane(buf))
	assert(vim.fn.jobwait({ vim.b[buf].terminal_job_id }, 0)[1] == -1)
end
assert(terminal.focus(second), 'adopted split remains accessible')
settle()
assert(vim.api.nvim_get_current_buf() == second)
-- An empty destination receives the workspace without opening it.
vim.cmd('tabnew')
local empty = vim.api.nvim_get_current_tabpage()
vim.api.nvim_set_current_tabpage(destination)
vim.cmd('tabclose!')
settle()
assert(vim.api.nvim_get_current_tabpage() == empty and not state.is_term_open())
assert(#state.get_tabs() == 3 and terminal.focus(hidden))
-- Closing a background tab and :tabonly also adopt into the current tab.
vim.cmd('tabnew')
local background = vim.api.nvim_get_current_tabpage()
local background_buf = terminal.new()
vim.api.nvim_set_current_tabpage(empty)
vim.cmd(vim.api.nvim_tabpage_get_number(background) .. 'tabclose!')
settle()
assert(vim.b[background_buf].term_owner_tab == empty and #state.get_tabs() == 4)
vim.cmd('tabnew')
local extra = terminal.new()
vim.api.nvim_set_current_tabpage(empty)
vim.cmd('tabonly!')
settle()
assert(vim.b[extra].term_owner_tab == empty and #state.get_tabs() == 5)
print('Tab closure transfer regressions passed')
