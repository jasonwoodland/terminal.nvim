local root = vim.fn.fnamemodify(arg[0], ":p:h:h")
vim.opt.runtimepath:prepend(root)
local ui = require("tests.helpers.ui").start(root, 120, 60)
local ok, err = pcall(function()
	ui.lua([[
		terminal = require('terminal')
		state = require('terminal.state')
		panes = require('terminal.panes')
		terminal.setup({height=20, keys={wincmd='<F6>'}, float={padding={x=4,y=3}}})
		function heights()
			local result = {}
			for _, win in ipairs(vim.t.term_winids) do result[#result+1] = vim.api.nvim_win_get_height(win) end
			return result
		end
		terminal.new()
		panes.resize(2, 'h')
		assert(state.drawer_span() == 22, 'single pane grows drawer')
		panes.resize(-2, 'h')
		assert(state.drawer_span() == 20, 'single pane shrinks drawer')
		terminal.hsplit()
		terminal.resize({height=21})
		terminal.equalize()
		assert(vim.deep_equal(heights(), {10,10}), vim.inspect(heights()))
	]])
	ui.input("<C-\\><C-n><F6>20<CR>")
	ui.wait("return vim.deep_equal(heights(), {1,20}) and state.drawer_span() == 22", "prefix borrows sibling space before growing drawer")
	ui.input("3<C-w>+")
	ui.wait("return vim.deep_equal(heights(), {1,23}) and state.drawer_span() == 25", "drawer grows once sibling reaches its minimum")
	ui.input("<F6>5-")
	ui.wait("return vim.deep_equal(heights(), {6,18}) and state.drawer_span() == 25", "shrinking returns space to sibling")
	ui.input("z12<CR>")
	ui.wait("return vim.deep_equal(heights(), {12,12})", "z height uses the same pane sizing")
	ui.input("15<C-w>_")
	ui.wait("return vim.deep_equal(heights(), {9,15})", "counted underscore sets pane height")
	ui.input("i")
	ui.wait("return vim.fn.mode() == 't'", "enter terminal input mode")
	ui.input("<F6>2+")
	ui.wait("return vim.deep_equal(heights(), {7,17}) and vim.fn.mode() == 't'", "terminal prefix resize preserves input mode")
	ui.lua([[
		panes.set_height(999)
		local _, available = require('terminal.size').available(false)
		assert(state.drawer_span() <= available and heights()[1] == 1, 'growth exhausts sibling space and clamps to screen')
		local span = state.drawer_span()
		panes.resize(-999, 'h')
		assert(heights()[2] == 1 and state.drawer_span() == span, 'shrink respects pane minimum and gives space to sibling')
		terminal.resize({height='50%'})
		panes.set_height(12)
		assert(not vim.t.term_drawer_size, 'pane sizing replaces percentage drawer size')
		saved_heights = heights()
		terminal.toggle({open=false})
		terminal.toggle({open=true})
		assert(vim.deep_equal(heights(), saved_heights), 'geometry survives reopening')
		terminal.vsplit()
		local before = heights()
		panes.set_height(16)
		assert(vim.deep_equal(heights(), {before[1]+before[2]-16,16,16}), 'shared row borrows from stacked neighbour')
		terminal.float_toggle()
		local cfg = require('terminal.window').get_float_win_config()
		panes.set_height(20)
		panes.resize(-2, 'h')
		assert(vim.deep_equal(cfg, require('terminal.window').get_float_win_config()), 'float bounds are unchanged')
		terminal.float_toggle()
		terminal.new()
		terminal.go_to(1)
		panes.set_height(14)
		assert(vim.api.nvim_win_get_height(vim.t.term_winid) == 14, 'pane sizing works with a visible terminal tab bar')
		terminal.new()
		terminal.vsplit()
		terminal.hsplit()
		terminal.resize({height=31})
		terminal.equalize()
		local before, span = heights(), state.drawer_span()
		panes.resize(3, 'h')
		local after = heights()
		assert(after[1] == before[1] and after[2] == before[2]-3 and after[3] == before[3]+3
			and state.drawer_span() == span, 'pane 3 borrows from pane 2 without growing the drawer or pane 1')
		assert(vim.v.errmsg == '', vim.v.errmsg)
	]])
end)
ui.close()
assert(ok, err)
print("Drawer pane resizing passed")
