local root = vim.fn.fnamemodify(arg[0], ":p:h:h")
vim.opt.runtimepath:prepend(root)
local helper = require("tests.helpers.ui")
local ui = helper.start(root)
ui.lua("vim.schedule(function() vim.g.health_probe_ran=true; error('asynchronous-health-probe') end)")
ui.wait("return vim.g.health_probe_ran == true", "asynchronous probe ran")
local ok, err = pcall(ui.close)
assert(not ok and tostring(err):find("asynchronous%-health%-probe"), "scheduled child errors must fail teardown")
ui = helper.start(root)
pcall(ui.lua, "vim.cmd('cquit 7')")
ok, err = pcall(ui.close)
assert(not ok and tostring(err):find("code 7",1,true), "abnormal child exit must fail teardown")
ui = helper.start(root)
pcall(ui.lua, "vim.cmd('qa!')")
ok, err = pcall(ui.close)
assert(not ok and tostring(err):find("before teardown",1,true), "unexpected clean child exit must fail teardown")
print("Attached-UI health checks passed")
