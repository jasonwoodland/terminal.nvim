local root = vim.fn.fnamemodify(arg[0], ":p:h:h")
vim.opt.runtimepath:prepend(root)
local ui = require("tests.helpers.ui").start(root, 120, 50)
local ok, err = pcall(function()
	ui.lua([[
		terminal = require('terminal')
		state = require('terminal.state')
		window = require('terminal.window')
		terminal.setup({keys=false})
		function failed(action, ...)
			local ok, reason = action(...)
			assert(ok == false and type(reason) == 'string')
		end
		failed(terminal.move, 1)
		failed(terminal.move_to_vim_tab, 1)
		failed(terminal.break_pane_to_tab)
		one = terminal.new()
		assert(terminal.move(1), 'one tab is a successful no-op')
		failed(terminal.move_to_vim_tab, 1)
		failed(terminal.break_pane_to_tab)
		two = terminal.new()
		local id = state.get_current_tab().id
		terminal.toggle({open=false})
		local win = vim.api.nvim_get_current_win()
		assert(terminal.move(-1))
		assert(state.get_current_tab().id == id and vim.t.term_tab_idx == 1 and not state.is_term_open())
		assert(vim.api.nvim_get_current_win() == win and vim.t.term_bufnr == two)
		assert(terminal.move(-1) and vim.t.term_tab_idx == 2, 'reordering wraps')
		for _, value in ipairs({false, 0, 2, -2, 1.5, '1', {}, math.huge, 0/0}) do
			failed(terminal.move, value)
			failed(terminal.move_to_vim_tab, value)
		end
		failed(terminal.move)
		failed(terminal.move_to_vim_tab)
		assert(state.get_current_tab().id == id and vim.t.term_tab_idx == 2 and not state.is_term_open())
		terminal.toggle({open=true})
		pane = terminal.vsplit()
		source = vim.api.nvim_get_current_tabpage()
		vim.cmd('tabnew')
		destination = vim.api.nvim_get_current_tabpage()
		vim.api.nvim_set_current_tabpage(source)
	]])
	ui.input("<C-\\><C-n>")
	ui.wait("return vim.fn.mode() == 'n'", "normal mode ready")
	ui.lua([[
		local before, wins = state.get_tabs(), vim.deepcopy(vim.t.term_winids)
		local can_open, notify = window.can_open_tab, vim.notify
		vim.notify = function() end
		window.can_open_tab = function() return false end
		failed(terminal.break_pane_to_tab)
		window.can_open_tab = function(...)
			return vim.api.nvim_get_current_tabpage() ~= destination and can_open(...)
		end
		failed(terminal.move_to_vim_tab, 1)
		window.can_open_tab, vim.notify = can_open, notify
		assert(vim.deep_equal(before, state.get_tabs()) and vim.deep_equal(wins, vim.t.term_winids), 'failed fit checks preserve source')
		assert(#state.get_tabs(destination) == 0 and vim.b[pane].term_owner_tab == source)
		assert(terminal.move_to_vim_tab(1))
		assert(vim.api.nvim_get_current_tabpage() == destination and vim.api.nvim_get_current_buf() == pane)
		assert(vim.b[pane].term_owner_tab == destination and #state.get_tabs(source) == 1)
		assert(terminal.break_pane_to_tab())
		assert(#state.get_tabs() == 2 and #state.get_current_tab().bufs == 1 and vim.api.nvim_get_current_buf() == pane)
		failed(terminal.break_pane_to_tab)
		assert(terminal.move_to_vim_tab(-1))
		assert(vim.api.nvim_get_current_tabpage() == source and vim.b[pane].term_owner_tab == source)
		assert(vim.api.nvim_get_current_buf() == pane)
		vim.cmd('new')
		local editor = vim.api.nvim_get_current_win()
		failed(terminal.move_to_vim_tab, 1)
		failed(terminal.break_pane_to_tab)
		assert(vim.api.nvim_get_current_win() == editor)
		assert(vim.v.errmsg == '', vim.v.errmsg)
	]])
end)
ui.close()
assert(ok, err)
print("Terminal movement API passed")
