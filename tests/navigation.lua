local root = vim.fn.fnamemodify(arg[0], ":p:h:h")
vim.opt.runtimepath:prepend(root)
local ui = require("tests.helpers.ui").start(root)
local ok, err = pcall(function()
	ui.lua([[
		terminal = require('terminal')
		state = require('terminal.state')
		terminal.setup({keys={last_tab='<F8>'}})
		function failed(fn, ...)
			local ok, reason = fn(...)
			assert(ok == false and type(reason) == 'string')
		end
		failed(terminal.next)
		failed(terminal.prev)
		failed(terminal.switch, 1)
		failed(terminal.go_to, 1)
		one = terminal.new()
		two = terminal.new()
		three = terminal.new()
		terminal.toggle({open=false})
		editor = vim.api.nvim_get_current_win()
		function selected(index, buf)
			assert(vim.t.term_tab_idx == index and vim.t.term_bufnr == buf)
			assert(not state.is_term_open() and vim.api.nvim_get_current_win() == editor)
		end
		assert(terminal.go_to(1)); selected(1, one)
		assert(state.previous_tab_index() == 3)
		assert(terminal.prev()); selected(3, three)
		assert(terminal.next()); selected(1, one)
		assert(terminal.switch(-99, true)); selected(1, one)
		local previous = state.previous_tab_index()
		assert(terminal.switch(0) and terminal.go_to(1))
		assert(state.previous_tab_index() == previous, 'no-ops do not change history')
		assert(terminal.switch(99, true)); selected(3, three)
		assert(terminal.switch(-1)); selected(2, two)
		for _, value in ipairs({false, '1', {}, 1.5, math.huge, -math.huge, 0/0}) do
			failed(terminal.go_to, value)
			failed(terminal.switch, value)
		end
		failed(terminal.go_to)
		failed(terminal.switch)
		failed(terminal.go_to, 0)
		failed(terminal.go_to, 4)
		failed(terminal.switch, 1, 'true')
		selected(2, two)
	]])
	ui.input("<Esc><F8>")
	ui.wait("return vim.t.term_tab_idx == 3 and not state.is_term_open() and vim.fn.mode() == 'n'", "last tab selects without opening")
	ui.lua([[
		terminal.toggle({open=true})
		assert(vim.api.nvim_get_current_buf() == three, 'reopening uses hidden selection')
		assert(terminal.go_to(2) and vim.api.nvim_get_current_buf() == two)
		assert(terminal.next() and vim.api.nvim_get_current_buf() == three)
		assert(terminal.prev() and vim.api.nvim_get_current_buf() == two)
		local window, notify = require('terminal.window'), vim.notify
		local can_open = window.can_open_tab
		window.can_open_tab = function() return false end
		vim.notify = function() end
		failed(terminal.go_to, 1)
		window.can_open_tab, vim.notify = can_open, notify
		assert(vim.t.term_tab_idx == 2 and vim.api.nvim_get_current_buf() == two, 'failed switch keeps current selection')
		terminal.toggle({open=false})
		vim.cmd('tabnew')
		failed(terminal.next)
		assert(not state.is_term_open(), 'navigation is scoped to this Vim tab')
		vim.cmd('tabprevious')
		assert(vim.t.term_tab_idx == 2 and vim.t.term_bufnr == two)
		assert(vim.v.errmsg == '', vim.v.errmsg)
	]])
	ui.input("<Esc><C-S-1>")
	ui.wait("return state.is_term_open() and vim.api.nvim_get_current_buf() == one", "digit opens hidden tab")
	for _ = 4, 10 do ui.lua([[assert(terminal.new())]]) end
	ui.lua([[ten = state.get_tabs()[10].focus; assert(terminal.go_to(1))]])
	ui.lua([[assert(terminal.toggle({open=false}))]])
	ui.input("<Esc><C-S-0>")
	ui.wait("return state.is_term_open() and vim.api.nvim_get_current_buf() == ten", "zero opens tenth tab")
	ui.lua([[vim.cmd('tabnew')]])
	ui.input("<Esc><C-S-9>")
	ui.wait("return state.is_term_open() and #state.get_tabs() == 1", "digit starts first terminal in empty workspace")
end)
ui.close()
assert(ok, err)
print("Terminal tab navigation passed")
