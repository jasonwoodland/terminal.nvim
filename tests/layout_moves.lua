local root = vim.fn.fnamemodify(arg[0], ":p:h:h")
vim.opt.runtimepath:prepend(root)
local ui = require("tests.helpers.ui").start(root, 120, 50)
local ok, err = pcall(function()
	ui.lua([[
		local terminal = require('terminal')
		local state = require('terminal.state')
		local window = require('terminal.window')
		local frame = require('terminal.frame')
		local panes = require('terminal.panes')
		terminal.setup({keys=false})
		terminal.new()
		terminal.vsplit()
		terminal.hsplit()
		local focused = vim.api.nvim_get_current_buf()
		local height = state.drawer_span()
		for _, edge in ipairs({'bottom', 'top', 'left', 'right'}) do
			panes.splitmove(edge)
			window.save_layout_sizes()
			local layout = state.get_current_tab().layout
			local expected = vim.deepcopy(layout)
			frame.equalize(expected, expected.w, expected.h)
			assert(vim.deep_equal(layout, expected), edge .. ' equalizes the new layout: ' .. vim.inspect({layout, expected}))
			assert(state.drawer_span() == height, edge .. ' preserves drawer height')
			assert(vim.api.nvim_get_current_buf() == focused, edge .. ' preserves focus')
		end
	]])
end)
ui.close()
assert(ok, err)
print("Layout moves equalize panes and preserve drawer height")
