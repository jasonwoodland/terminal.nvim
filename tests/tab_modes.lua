-- Usage: nvim --clean --headless -l tests/tab_modes.lua
vim.opt.runtimepath:prepend(vim.fn.fnamemodify(arg[0], ":p:h:h"))
vim.env.SHELL = "/bin/sh"
vim.o.cmdheight, vim.o.ruler = 1, true
local terminal = require("terminal")
local config = require("terminal.config")
terminal.setup({ keys = false, set_buffer_name = false, float_zoom_hide_cmdline = true })
local function settle() vim.wait(160, function() return false end) end
terminal.toggle()
settle()
local source = vim.api.nvim_get_current_tabpage()
local height = vim.t.term_height
terminal.float_toggle()
settle()
assert(config.is_float_mode() and not terminal.config.float.enabled, "float toggle is local to the Vim tab")
vim.cmd("tabnew")
terminal.toggle()
settle()
local target = vim.api.nvim_get_current_tabpage()
assert(not config.is_float_mode() and vim.api.nvim_win_get_config(vim.t.term_winid).relative == "",
	"new Vim tab retains the configured drawer mode")
terminal.zoom()
settle()
assert(vim.o.cmdheight == 0 and not vim.o.ruler, "zoom applies its display options")
vim.cmd("tabnew")
settle()
assert(vim.o.cmdheight == 1 and vim.o.ruler, "new editor tab does not inherit zoom options")
vim.cmd("tabclose!")
settle()
assert(vim.o.cmdheight == 0 and not vim.o.ruler, "closing editor tab returns to zoom options")
vim.api.nvim_set_current_tabpage(source)
settle()
assert(config.is_float_mode() and not vim.t.term_zoom, "source remains an ordinary float")
assert(vim.o.cmdheight == 1 and vim.o.ruler, "leaving zoom restores options for another Vim tab")
terminal.float_toggle()
settle()
assert(vim.t.term_height == height, "float focus changes do not overwrite drawer height")
vim.api.nvim_set_current_tabpage(target)
settle()
assert(vim.o.cmdheight == 0 and not vim.o.ruler, "returning to zoom reapplies options")
terminal.zoom()
settle()
assert(not config.is_float_mode() and vim.o.cmdheight == 1 and vim.o.ruler, "unzoom restores drawer and options: " .. vim.inspect({ config.is_float_mode(), vim.o.cmdheight, vim.o.ruler, vim.t.term_zoom }))
terminal.zoom()
settle()
vim.cmd("tabclose!")
settle()
assert(vim.api.nvim_get_current_tabpage() == source and vim.o.cmdheight == 1 and vim.o.ruler,
	"closing a zoomed Vim tab restores options")
terminal.zoom()
settle()
local wins = vim.t.term_winids
for _, win in ipairs(wins) do vim.api.nvim_win_close(win, true) end
settle()
assert(vim.o.cmdheight == 1 and vim.o.ruler, "external pane closure releases zoom options")
print("Vim-tab mode regressions passed")
