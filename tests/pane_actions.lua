local root = vim.fn.fnamemodify(arg[0], ":p:h:h")
vim.opt.runtimepath:prepend(root)
local ui = require("tests.helpers.ui").start(root, 120, 50)
local ok, err = pcall(function()
	ui.lua([[
		terminal = require('terminal')
		state = require('terminal.state')
		terminal.setup({keys=false, float_zoom_hide_cmdline=true, float={padding={x=3,y=3}}})
		function failed(action, buf)
			local result, reason = action(buf)
			assert(result == false and type(reason) == 'string')
		end
		failed(terminal.delete)
		failed(terminal.reset)
		one = terminal.new({name='one'})
		two = terminal.vsplit({name='two'})
		original_tab = vim.api.nvim_get_current_tabpage()
	]])
	ui.wait("return vim.fn.mode() == 't'", "input mode ready")
	ui.lua([[
		assert(terminal.delete(one))
		assert(not vim.api.nvim_buf_is_valid(one) and vim.api.nvim_get_current_buf() == two)
	]])
	ui.wait("return vim.fn.mode() == 't' and vim.api.nvim_get_current_buf() == two", "deleting another pane preserves caller input mode")
	ui.lua([[
		local replacement = terminal.reset(two)
		assert(type(replacement) == 'number' and not vim.api.nvim_buf_is_valid(two))
		two = replacement
		assert(vim.api.nvim_get_current_buf() == two)
		hidden = terminal.new({name='hidden'})
		hidden_peer = terminal.hsplit()
		terminal.go_to(1)
		local selected, wins, current = vim.t.term_tab_idx, vim.deepcopy(vim.t.term_winids), vim.api.nvim_get_current_buf()
		local replacement = terminal.reset(hidden)
		assert(type(replacement) == 'number' and vim.b[replacement].terminal_custom_name == 'hidden')
		hidden = replacement
		assert(vim.t.term_tab_idx == selected and vim.deep_equal(wins, vim.t.term_winids) and vim.api.nvim_get_current_buf() == current)
		assert(terminal.delete(hidden_peer))
		assert(vim.t.term_tab_idx == selected and vim.deep_equal(wins, vim.t.term_winids))
		assert(terminal.delete(hidden))
		assert(#state.get_tabs() == 1 and vim.api.nvim_get_current_buf() == current)
		terminal.toggle({open=false})
		local editor = vim.api.nvim_get_current_win()
		local replacement = terminal.reset(two)
		assert(type(replacement) == 'number' and not state.is_term_open() and vim.api.nvim_get_current_win() == editor)
		two = replacement
		vim.cmd('tabnew')
		foreign = terminal.new({name='foreign'})
		foreign_peer = terminal.vsplit()
		foreign_tab = vim.api.nvim_get_current_tabpage()
		terminal.zoom()
		vim.api.nvim_set_current_tabpage(original_tab)
		terminal.toggle({open=true})
	]])
	ui.wait("return vim.fn.mode() == 't' and vim.api.nvim_get_current_buf() == two", "original workspace input mode restored")
	ui.lua([[
		local win, cmdheight = vim.api.nvim_get_current_win(), vim.o.cmdheight
		local termopen, before = vim.fn.termopen, state.get_tabs(foreign_tab)
		local wins, count = vim.deepcopy(vim.t[foreign_tab].term_winids), #vim.api.nvim_list_bufs()
		vim.fn.termopen = function() error('injected foreign launch failure') end
		failed(terminal.reset, foreign)
		vim.fn.termopen = termopen
		assert(vim.deep_equal(before, state.get_tabs(foreign_tab)) and vim.deep_equal(wins, vim.t[foreign_tab].term_winids))
		assert(#vim.api.nvim_list_bufs() == count and vim.api.nvim_get_current_win() == win and vim.o.cmdheight == cmdheight)
		local replacement = terminal.reset(foreign)
		assert(type(replacement) == 'number')
		assert(vim.b[replacement].term_owner_tab == foreign_tab)
		assert(vim.api.nvim_get_current_tabpage() == original_tab and vim.api.nvim_get_current_win() == win)
		assert(vim.o.cmdheight == cmdheight)
		assert(terminal.delete(foreign_peer))
		assert(vim.api.nvim_get_current_tabpage() == original_tab and vim.api.nvim_get_current_win() == win)
		assert(vim.o.cmdheight == cmdheight, 'foreign zoom must not leak command-line settings')
		foreign = replacement
	]])
	ui.wait("return vim.fn.mode() == 't' and vim.api.nvim_get_current_buf() == two", "foreign pane actions preserve input mode")
	ui.lua([[
		vim.api.nvim_set_current_tabpage(foreign_tab)
		terminal.toggle({open=false})
		vim.api.nvim_set_current_tabpage(original_tab)
		local replacement = terminal.reset(foreign)
		assert(type(replacement) == 'number' and #vim.t[foreign_tab].term_winids == 0)
		assert(terminal.delete(replacement) and #state.get_tabs(foreign_tab) == 0)
		assert(vim.api.nvim_get_current_tabpage() == original_tab and vim.api.nvim_get_current_buf() == two)
		failed(terminal.delete, foreign)
		failed(terminal.reset, replacement)
		for _, buf in ipairs({false, -1, 'invalid', 999999}) do
			failed(terminal.delete, buf)
			failed(terminal.reset, buf)
		end
		vim.cmd('stopinsert')
		vim.cmd('new')
		vim.cmd('terminal')
		local ordinary = vim.api.nvim_get_current_buf()
		failed(terminal.delete, ordinary)
		failed(terminal.reset, ordinary)
		assert(vim.api.nvim_buf_is_valid(ordinary))
		assert(vim.v.errmsg == '', vim.v.errmsg)
	]])
end)
ui.close()
assert(ok, err)
print("Targeted terminal pane actions passed")
