-- Usage: nvim --clean --headless -l tests/focus.lua
vim.opt.runtimepath:prepend(vim.fn.fnamemodify(arg[0], ":p:h:h"))
vim.env.SHELL = "/bin/sh"
local terminal = require("terminal")
local state = require("terminal.state")
terminal.setup({ keys = false, set_buffer_name = false })
local function settle() vim.wait(150, function() return false end) end
local function focused(buf)
	settle()
	assert(vim.api.nvim_get_current_buf() == buf, "focus lands on requested pane")
	assert(vim.t.term_bufnr == buf and vim.api.nvim_get_current_win() == vim.t.term_winid,
		"focused pane is tracked")
	assert(state.get_current_tab().focus == buf, "entry remembers selected pane")
end
assert(#terminal.list() == 0 and not package.loaded["telescope"], "core has no Telescope dependency")
terminal.toggle()
settle()
local source = vim.api.nvim_get_current_tabpage()
local original = vim.api.nvim_get_current_buf()
terminal.new()
settle()
terminal.vsplit()
settle()
terminal.hsplit()
settle()
local target = vim.api.nvim_get_current_buf()
local entry_id = state.get_current_tab().id
vim.b[target].term_mode = "n"
local list = terminal.list()
assert(#list == 4, "lists every managed pane")
assert(list[4].bufnr == target and list[4].tabpage == source and list[4].tab_id == entry_id
	and list[4].tab_index == 2 and list[4].pane_index == 3, "list includes workspace coordinates")
list[4].title = "changed"
assert(terminal.list()[4].title ~= "changed", "listing returns detached metadata")
terminal.go_to(1)
settle()
terminal.toggle()
settle()
vim.cmd("tabnew")
settle()
local editor_tab = vim.api.nvim_get_current_tabpage()
local editor_buf = vim.api.nvim_get_current_buf()
local editor_win = vim.api.nvim_get_current_win()
assert(#terminal.list() == 4 and vim.api.nvim_get_current_win() == editor_win,
	"listing includes hidden panes across Vim tabs without moving focus")
assert(terminal.focus(target))
focused(target)
assert(vim.api.nvim_get_current_tabpage() == source and vim.t.term_tab_idx == 2,
	"opens the requested hidden group in the owning Vim tab")
assert(vim.api.nvim_buf_get_name(editor_buf) == "" and vim.api.nvim_win_get_buf(editor_win) == editor_buf,
	"editor window is untouched")
assert(vim.b[target].term_mode == "n", "Normal-mode preference survives navigation")
assert(terminal.focus(original))
focused(original)
assert(state.previous_tab_index() == 2, "focus updates terminal-tab history")
assert(terminal.focus(target))
focused(target)
terminal.move(-1)
settle()
vim.api.nvim_set_current_tabpage(editor_tab)
settle()
assert(terminal.focus(target))
focused(target)
assert(vim.t.term_tab_idx == 1, "focus resolves reordered entries")
terminal.move_to_vim_tab(1)
settle()
assert(vim.api.nvim_get_current_tabpage() == editor_tab, "workspace moved to adjacent Vim tab")
vim.api.nvim_set_current_tabpage(source)
settle()
assert(terminal.focus(target))
focused(target)
assert(vim.api.nvim_get_current_tabpage() == editor_tab, "focus resolves moved ownership")
terminal.float_toggle()
settle()
assert(terminal.focus(terminal.list()[2].bufnr))
settle()
assert(vim.api.nvim_win_get_config(vim.api.nvim_get_current_win()).relative == "editor",
	"focus preserves floating mode")
state.set_last_notification_bufnr(target)
terminal.go_to_notification()
focused(target)
local current_win = vim.api.nvim_get_current_win()
local current_tab = vim.api.nvim_get_current_tabpage()
assert(not terminal.focus(editor_buf), "unmanaged buffers are rejected")
assert(vim.api.nvim_get_current_win() == current_win and vim.api.nvim_get_current_tabpage() == current_tab,
	"invalid selection does not navigate")
terminal.delete()
settle()
assert(not terminal.focus(target), "closed picker entries are rejected")
print("Terminal listing and focus regressions passed")
