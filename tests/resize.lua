local root = vim.fn.fnamemodify(arg[0], ":p:h:h")
vim.opt.runtimepath:prepend(root)
local ui = require("tests.helpers.ui").start(root, 120, 60)
local ok, err = pcall(function()
	ui.lua([[
		terminal = require('terminal')
		state = require('terminal.state')
		window = require('terminal.window')
		size = require('terminal.size')
		terminal.setup({ height = 20, float = { padding = { x = 4, y = 3 }, border = 'rounded' } })
		vim.o.showtabline = 2
		editor = vim.api.nvim_get_current_win()
		terminal.new()
		terminal.hsplit()
	]])
	ui.wait("return #vim.t.term_winids == 2", "two panes open")
	ui.lua([[
		local before = vim.api.nvim_win_get_height(vim.t.term_winids[1]) / (state.drawer_span() - 1)
		assert(terminal.resize({height = 30}))
		assert(state.drawer_span() == 30, vim.inspect(state.drawer_span()))
		local wins = vim.t.term_winids
		assert(math.abs(vim.api.nvim_win_get_height(wins[1]) / 29 - before) < .06,
			'resize retains pane proportions')
		local buffers = vim.deepcopy(state.get_current_tab().bufs)
		for _, opts in ipairs({{width=30}, {height=0}, {height='101%'}, {height=999}, {rows=20}, {height=1}}) do
			local ok, reason = terminal.resize(opts)
			assert(ok == false and type(reason) == 'string', vim.inspect(opts))
			assert(state.drawer_span() == 30 and vim.deep_equal(buffers, state.get_current_tab().bufs))
		end
		vim.cmd('TermResize 50%')
		local _, available = size.available(false)
		assert(state.drawer_span() == math.floor(available / 2))
		vim.api.nvim_set_current_win(editor)
		assert(terminal.resize({height=24}))
		assert(vim.api.nvim_get_current_win() == editor, 'resize preserves editor focus')
	]])
	ui.wait("return vim.fn.mode() == 'n'", "resize preserves editor mode")
	ui.lua([[
		assert(terminal.resize())
		assert(state.drawer_span() == 20)
		assert(terminal.resize({height='50%'}))
	]])
	ui.request("nvim_ui_try_resize", 140, 70)
	ui.wait([[local _, available = size.available(false); return state.drawer_span() == math.floor(available / 2)]], "percentage drawer follows screen resize")
	ui.wait("return vim.api.nvim_get_current_win() == editor and vim.fn.mode() == 'n'", "screen resize preserves editor focus")
	ui.lua([[
		terminal.float_toggle()
		assert(terminal.resize({width=100,height=30}))
		local cfg = window.get_float_win_config()
		assert(cfg.width == 100 and cfg.height == 30)
		local aw, ah, row = size.available(true)
		assert(cfg.col == math.floor((aw - 100)/2) and cfg.row == row + math.floor((ah - 30)/2))
		vim.cmd('TermResize 80%x50%')
		cfg = window.get_float_win_config()
		assert(cfg.width == math.floor(aw*.8) and cfg.height == math.floor(ah*.5))
		assert(terminal.resize({height=24}))
		assert(window.get_float_win_config().width == math.floor(aw*.8), 'partial sizing retains width')
		terminal.zoom()
		assert(terminal.resize({height=28}))
		assert(not vim.t.term_zoom and window.get_float_win_config().height == 28, 'resize exits zoom')
		terminal.resize()
		cfg = window.get_float_win_config()
		assert(cfg.col == 4 and cfg.row == 3 and cfg.width == vim.o.columns - 10)
		for _, input in ipairs({'20 30','20,30','20 x 30','20X30','0','101%','10x','-5'}) do
			assert(not size.parse(input), input .. ' must be rejected')
		end
		vim.cmd('TermResize 100x30')
		assert(window.get_float_win_config().width == 100)
		terminal.toggle({open=false})
		assert(terminal.resize({height=26}))
		assert(not state.is_term_open(), 'hidden resize does not open terminals')
		vim.cmd('tabnew')
		assert(not vim.t.term_float_size and not vim.t.term_drawer_size, 'sizes belong to their Vim tab')
		vim.cmd('tabprevious')
		terminal.toggle({open=true})
		assert(window.get_float_win_config().height == 26)
		terminal.vsplit()
		local action = vim.fn.maparg('<C-S-=>', 'n', false, true).callback
		assert(type(action) == 'function')
		action()
		assert(window.get_float_win_config().height == 26, 'equalize does not reset workspace size')
		local tree = state.get_current_tab().layout
		assert(math.abs(tree.children[1].h - tree.children[2].h) <= 1, 'equalizes stacked panes')
		local row = tree.children[2]
		assert(row.t == 'row' and math.abs(row.children[1].w - row.children[2].w) <= 1, 'equalizes side-by-side panes')
	]])
end)
ui.close()
assert(ok, err)
print("Workspace resize passed")
